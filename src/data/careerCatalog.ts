function makeCareer(name: string, group: CatalogGroup): CareerDefinition {
  const traits = careerTraitProfiles[name];
  if (!traits) {
    throw new Error(`Missing meaning-based career traits for ${name}`);
  }
  const activityTags = {
    ...group.activityTags,
    ...traits.activityTags,
  };
  const workStyleTags = {
    ...group.workStyleTags,
    ...traits.workStyleTags,
  };

  return {
    name,
    libraryCategory: group.title,
    primaryField: group.primaryField,
    secondaryField: group.secondaryField,
    activityTags,
    workStyleTags,
    detail: {
      name,
      emoji: group.emoji,
      tagline: group.tagline,
      description: `${name}은 ${group.description} 그래서 관심 있는 활동을 해 보며 나에게 맞는지 천천히 알아갈 수 있어요.`,
      dailyTasks: group.dailyTasks,
      workPlaces: group.workPlaces,
      skills: group.skills,
      schoolActivities: group.schoolActivities,
      growthSteps: group.growthSteps,
      funFact: group.funFact,
    },
  };
}

